ADDRESS_RE = re.compile(
    r"\d{1,5}[\d,.]*\s+(?:[A-Z][\w'.-]*\s+){1,4}"
    r"(?:Street|Avenue|Ave|Boulevard|Blvd|Road|Drive|Way|Parkway|Place|Court|Lane|Circle|Terminals?)\b"
    r"|\bBuilding \d+[A-Z]?\b|\bAlameda Point\b|\bAlameda,? California\b|\bAlameda,? CA\b",
    re.I)


def categorize(text):
    # Strip street-address / place-name fragments first so an incidental
    # "2701 Monarch Street" or "Building 20" doesn't win a category match
    # over the item's actual subject (a lease is Economic Development even
    # though its address contains the word "Street"). Also strip "Animal
    # Shelter" so it doesn't trip the Housing rule's bare "shelter" keyword.
    t = ADDRESS_RE.sub(" ", text or "")
    t = re.sub(r"\bAnimal Shelter\b", " ", t, flags=re.I).lower()
    for cat, pattern in CATEGORY_RULES:
        if re.search(pattern, t):
            return cat
    return "Other"


# --------------------------------------------------------------- cleanup
def clean_ws(s):
    return re.sub(r"\s+", " ", s or "").strip()


def strip_trailing_status(s):
    s = re.sub(r"\s*(Accepted|Approved|Adopted|Introduced|Passed|Finally passed|"
               r"Final(?:ly)? [Pp]assed)\.?\s*;?\s*(and)?\s*$", "", s, flags=re.I)
    return s.rstrip(' ;."”').strip()


OFFICIAL_STATUS_RE = re.compile(r"(?:(?<=[.\"”)\]])|[;:]|\.[;:])\s*(?:Finally passed|Introduced|Adopted|Approved|Accepted|Not adopted|Not heard|Failed|"
                                r"Continued|Withdrawn|Received|Heard)(?:\s+and)?\.?\s*;?\s*(?:and)?\s*$", re.I)


def fix_encoding(s):
    """The City's PDF-to-text turns the section sign and accented letters into U+FFFD."""
    if not s or "\ufffd" not in s:
        return s
    s = re.sub(r"(Code|Section|Sections) ?\ufffd ?", lambda m: f"{m.group(1)} § ", s)
    return s.replace("Caf\ufffd", "Café").replace("Fa\ufffdade", "Façade").replace("Sullivan-Seri\ufffdana", "Sullivan-Sarinana")


def tidy_official(t):
    """The official title as the agenda wrote it: without the clerk's action word
    ("... Adopted; and") that follows it in the minutes, or a dangling "; and"."""
    t = clean_ws(t)
    t = OFFICIAL_STATUS_RE.sub("", t)
    t = re.sub(r"(?<=[.\"”)\]])\s+(?:Finally|Final|Intr\w*|Adop\w*|Appro\w*|Acce\w*)$", "", t)   # status word clipped by the 300-character cut
    t = re.sub(r"\s*\[(?:Continued|Not heard)[^\]]*\]\s*$", "", t, flags=re.I)
    t = re.sub(r"\s*;\s*and\s*$", "", t)
    return t.rstrip(" ;,:")


def money(s):
    return clean_ws(s).replace(" ", "")


# Small, closed-vocabulary conjugation helpers. Titles hand us a bare
# infinitive ("Award", "Consider", "Name") that needs to become either
# third-person-singular-present ("Awards") or a gerund ("Considering") to
# read as a grammatical sentence -- .capitalize() alone just re-cases the
# string, it doesn't conjugate, which produced things like "Award a
# Contract..." (missing the -s) and "Recommends consider..." (missing -ing).
THIRD_PERSON_IRREGULAR = {
    "ratify": "ratifies", "reaffirm": "reaffirms", "endorse": "endorses",
    "adopt": "adopts", "award": "awards",
}


def third_person(verb):
    v = verb.lower()
    conj = THIRD_PERSON_IRREGULAR.get(v)
    if conj is None:
        conj = v[:-1] + "ies" if v.endswith("y") and v[-2:-1] not in "aeiou" else v + "s"
    return conj[0].upper() + conj[1:]


def gerund(verb):
    v = verb.lower()
    if v.endswith("ie"):
        g = v[:-2] + "ying"
    elif v.endswith("e") and not v.endswith("ee"):
        g = v[:-1] + "ing"
    else:
        g = v + "ing"
    return g[0].upper() + g[1:]


def lead_gerund(rest):
    """`rest` is whatever followed "Recommendation to " in the official
    title, so its first word is always a bare infinitive verb (Consider,
    Name, Direct, Amend, ...) -- turn it into a gerund so "Recommends " +
    this reads as one verb, not two ("Recommends consider..." -> "Recommends
    considering...")."""
    head, _, tail = rest.partition(" ")
    trailing_colon = head.endswith(":")
    if trailing_colon:
        head = head[:-1]
    return f"{gerund(head)}{':' if trailing_colon else ''} {tail}".strip()


