def redact_emails(text):
    """Agenda titles occasionally quote a private group's email address; the
    published record replaces any address with a placeholder."""
    return EMAIL_RE.sub("[email address redacted]", text)



def is_override(t):
    """True when a hand-written override (keyed to the 300-char title) supplies this item."""
    if t in MANUAL or t in MANUAL2:
        return True
    m = re.search(r'(?:Resolution|Ordinance)\s+(?:No\.?[_\s]*)?([\dA-Za-z]+)', t)
    return bool(m and m.group(1) in RESO_ORD_OVERRIDES)


