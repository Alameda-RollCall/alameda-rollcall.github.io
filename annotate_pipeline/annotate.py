def simplify_contract_clause(text):
    """Turn 'an/a [N-Year] Agreement with VENDOR ... for PURPOSE ... Not-to-Exceed $X'
    into a plain sentence. Falls back to a trimmed version of `text` if the
    shape doesn't match."""
    m = re.search(
        r"with (?P<vendor>[A-Z][\w&,.'/ -]+?),?\s+(?:in an Amount|for)"
        r".{0,140}?Not.to.Exceed\s*\$(?P<amt>[\d,]+(?:\.\d+)?)",
        text)
    vendor = m.group("vendor").strip(" ,") if m else None
    amt = m.group("amt") if m else None

    purpose = None
    pm = re.search(r"for (?:the )?(?P<purpose>[A-Z][^.;]{5,120}?)(?:,? in an Amount|,? Not.to.Exceed|$)", text)
    if pm:
        purpose = clean_ws(pm.group("purpose"))

    if vendor and amt:
        if purpose and vendor.lower() not in purpose.lower():
            return f"Authorizes a contract with {vendor} for {purpose}, not to exceed ${amt}."
        return f"Authorizes a contract with {vendor}, not to exceed ${amt}."
    if vendor:
        return f"Authorizes a contract with {vendor}" + (f" for {purpose}." if purpose else ".")
    return None


def summarize_resolution_text(quoted):
    """quoted = the text inside the Resolution/Ordinance's quotation marks;
    returns a verb-led, plain-English sentence (see summary_text.py)."""
    return effect_sentence(quoted)


def that_clause(text):
    """Lower-case the leading verb so the effect reads after "an ordinance that"."""
    e = effect_sentence(text).rstrip(".")
    return e[:1].lower() + e[1:]


