def also_categories(title, main):
    t = (title or "").lower()
    out = []
    if re.match(r"conference with|public employee|recommendation to approve [^,]{3,40}, (?:interim |acting )?city manager", t):
        if ALAMEDA_POINT_RE.search(t) and main != "Alameda Point":
            out.append("Alameda Point")
        if "real property" in t or "negotiators" in t and re.search(r"property|building|lease", t):
            out.append("Real Property & Leases")
        if re.search(r"labor negotiators|performance evaluation", t):
            out.append("Labor & Workforce")
        return out
    if ALAMEDA_POINT_RE.search(t) and main != "Alameda Point":
        out.append("Alameda Point")
    for tag, pat in TOPIC_TAG_RULES:
        if tag == "Policing & Civil Liberties" and re.search(r"retiree|benefit|memorandum of understanding|impact fee|salary|dental", t):
            continue
        if re.search(pat, t):
            out.append(tag)
    for cat, pat in ALSO_RULES:
        if cat != main and re.search(pat, t):
            out.append(cat)
    return out

