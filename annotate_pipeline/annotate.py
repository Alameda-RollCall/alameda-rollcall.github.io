def annotate(title):
    t = clean_ws(title)
    if t in MANUAL:
        return MANUAL[t]
    if t in MANUAL2:
        return MANUAL2[t]
    # The scraper clips titles at 300 characters; drop the clipped last word so
    # summaries don't end in fragments like "...Execu".
    # (clipped titles are exactly 299-300 characters after whitespace cleanup; a
    # longer title is the complete one and keeps its last word)
    if len(t) in (299, 300) and not t.endswith((".", '"', ")", "”")):
        t = t.rsplit(" ", 1)[0]
    t = re.sub(r"\bto Authorizing\b", "to Authorize", t)
    # Strip scraper-boundary artifacts: a leftover sub-item letter marker
    # ("(A) Introduction of..."), a stray Legistar item-id prefix
    # ("2016-2539 Consider..."), and a trailing page/item bracket ref
    # ("... Report. [270-30]").
    t = re.sub(r"^\([A-Z]\)\s*", "", t)
    t = re.sub(r"^\d{4}-\d+\s+", "", t)
    t = re.sub(r"\s*\[\d+-\d+\]\s*$", "", t)
    # a referral's sponsor, "(Councilmember Daysog)", stays in the official title only
    t = re.sub(r"\s*\((?:Mayor|Vice Mayor|Councilmembers?|Council Members?)[^)]*\)", "", t, flags=re.I)
    t = re.sub(r"\s*\((?:Continued|Not heard)[^)]*\)|\s*\[(?:Continued|Not heard)[^\]]*\]", "", t, flags=re.I).rstrip()

    # -- Continued <item> -- the clerk carried an item over from a prior
    # meeting; strip the prefix and annotate the underlying item itself ----
    if t.startswith("Continued "):
        return annotate(t[len("Continued "):])
    # -- Supplemental Report Regarding <item> -- same idea, different wording
    m = re.match(r"^Supplemental Report Regarding (?:the )?(.+)$", t)
    if m:
        cat, summ = annotate(m.group(1))
        return (cat, f"Supplemental report: {lc_first(summ)}") if cat and summ else (None, None)

    # -- Ratified bills -------------------------------------------------
    if re.match(r"^Bills for ratification$", t, re.I):
        return "Budget & Finance", "Approves routine payment of city bills."
    m = re.match(r"^Ratified [Bb]ills in the amount of \$?\s*\$?([\d,. ]+)$", t, re.I)
    if m:
        return "Budget & Finance", f"Approves routine payment of city bills totaling ${money(m.group(1))}."
    if re.match(r"^Ratified [Bb]ills in the amount of", t, re.I):
        # Two-payroll-period titles ("... $7,073,054.05 and $4,963,056.55")
        # aren't worth parsing into a single total -- state it plainly.
        return "Budget & Finance", "Approves routine payment of city bills."

    # -- Minutes ----------------------------------------------------------
    if re.match(r"^Minutes of the", t) or re.match(r"^of the .*(?:Meeting|Meetings)\b", t):
        dm = re.search(r"Held on ([A-Za-z]+ \d{1,2}, \d{4})", t)
        when = dm.group(1) if dm else None
        return "Governance", (f"Certifies the written minutes of the council meeting(s) of {when} as the official record."
                               if when else "Certifies the written minutes of the council meeting(s) as the official record.")

    # -- Public comment rows leaked into the parser -----------------------
    if re.search(r",\s*Alameda,\s*(made|offered) (brief )?comments?$", t, re.I) or \
       re.search(r"invited (people|the public|everyone) to attend", t, re.I):
        return "Other", None  # flagged for manual review, see spot-check pass

    # -- Resolution/Ordinance [No.] NNNN -- hand-authored plain-English pass
    # ("No." is sometimes omitted entirely: "Resolution 16193, ..."; an
    # underscore sometimes stands in for the space: "No._15144") -----------
    m = re.search(r'(?:Resolution|Ordinance)\s+(?:No\.?[_\s]*)?([\dA-Za-z]+)', t)
    if m and m.group(1) in RESO_ORD_OVERRIDES:
        return RESO_ORD_OVERRIDES[m.group(1)]

    # -- Resolution/Ordinance [No.] NNNN, "..." (title is truncated to 300
    # chars at the source, so long items sometimes never reach a closing
    # quote -- fall back to "everything after the opening quote"; the
    # separator before the quote is usually a comma but is sometimes a
    # semicolon) ------------------------------------------------------------
    m = re.search(r'(?:Resolution|Ordinance)\s+(?:No\.?[_\s]*)?[\dA-Za-z]+[,;]?\s*"(.+?)"', t)
    if not m:
        m = re.search(r'(?:Resolution|Ordinance)\s+(?:No\.?[_\s]*)?[\dA-Za-z]+[,;]?\s*"(.+)$', t)
    if m:
        q = strip_trailing_status(m.group(1))
        return categorize(q), summarize_resolution_text(q)
    # occasional missing open-quote typo: 'Resolution No. 16261, Adopting the...'
    m = re.match(r'^Resolution\s+(?:No\.?[_\s]*)?[\dA-Za-z]+[,;]\s*(.+)$', t)
    if m:
        q = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(q), summarize_resolution_text(q)
    # no quotes at all, comma/semicolon optional: 'Ordinance No. 3321, Concerning Rent ...'
    m = re.match(r'^(?:Resolution|Ordinance)\s+No\.?[_\s]*[\dA-Za-z]+[,;]?\s+(.+)$', t)
    if m:
        q = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(q), summarize_resolution_text(q)

    # -- Public Hearing to Consider Resolution [No.] NNNN, "..." -----------
    m = re.match(r'^Pub[l]?ic Hearing to [Cc]onsider Resolution\s+(?:No\.?\s*)?[\dA-Za-z]+,?\s*"(.+?)"', t)
    if m:
        q = m.group(1)
        return categorize(q), f"Public hearing: {lc_first(summarize_resolution_text(q))}"

    # -- Adoption of Resolution .../ Final Passage of Ordinance ... (no
    # quoted text at all -- the clerk describes it in plain prose instead) --
    m = re.match(r'^Adoption of Resolution\s+(.+)$', t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Adopts a resolution that {that_clause(rest)}."
    # "Final Passage of Ordinance ..." or, less often, "Final Passage of
    # <the ordinance's own descriptive name> Ordinance ..." (word order
    # varies, so only require the phrase to start with "Final Passage of")
    m = re.match(r'^Final Passage of (?:Ordinance\s+)?(.+)$', t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Gives final approval to an ordinance that {that_clause(rest)}."
    # "Adoption of Reappointing X ..." / "Adoption of Appointing X ..." -- no
    # "Resolution" word at all, just the operative verb directly
    m = re.match(r'^Adoption of ((?:Ree?appointing|Appointing)\s+.+)$', t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return "Governance", f"{rest[0].upper()}{rest[1:]}."

    # -- Introduction of [an/uncodified] Ordinance ... (mirrors the eventual
    # "finally passed") ------------------------------------------------------
    m = re.match(r"^Introduction of (?:an? )?(?:[Uu]ncodified )?Ordinance\s*(.+)$", t)
    if m:
        rest = strip_trailing_status(m.group(1))
        return categorize(rest), f"Gives initial approval to an ordinance that {that_clause(rest)}." if rest else None

    # -- Public Hearing to Consider Introduction of Ordinance ... ----------
    m = re.match(r"^Public Hearing to [Cc]onsider Introduction of Ordinance\s*(.+)$", t)
    if m:
        rest = strip_trailing_status(m.group(1))
        return categorize(rest), f"Public hearing on an ordinance that {that_clause(rest)}." if rest else None

    # -- Public Hearing and Consider .../ Conduct a Public Hearing and
    # Consider ... (a hearing bundled with the substantive item in one title)
    m = re.match(r"^(?:Public Hearing and Consider|Conduct a Public Hearing and Consider)\s+(.+)$", t)
    if m:
        cat, summ = annotate(m.group(1))
        if cat and summ:
            return cat, f"Public hearing: {lc_first(summ)}"
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Public hearing: considers {lc_first(rest)}."

    # -- Public Hearing to Provide Direction on .../ Workshop to Provide
    # Direction on ... -------------------------------------------------------
    m = re.match(r"^(?:Public Hearing|Workshop) to Provide Direction on\s+(.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        lead = "Public hearing" if t.lower().startswith("public hearing") else "Workshop"
        return categorize(rest), f"{lead}: gives staff direction on {lc_first(rest)}."

    # -- Budget Workshop for Fiscal Year(s) ... ------------------------------
    if t.startswith("Budget Workshop for Fiscal Year"):
        return "Budget & Finance", "Gives staff budget-priority direction ahead of the formal budget adoption hearing."

    # -- Public Hearing to Consider <other> ---------------------------------
    m = re.match(r"^Pub[l]?ic Hearing to [Cc]onsider(?: an)?\s*(.+)$", t)
    if m:
        rest = strip_trailing_status(m.group(1))
        return categorize(rest), f"Public hearing to consider {lc_first(rest)}." if rest else None

    # -- Conference with Real Property Negotiators -------------------------
    if re.match(r"^Conference [Ww]ith Real Property Negotiators", t):
        pm = re.search(r"Property:\s*([^;]+)", t)
        prop = clean_ws(pm.group(1)) if pm else "city-owned property"
        return "Economic Development", f"Authorizes closed-session negotiations regarding {prop}."

    # -- Conference with Labor Negotiators ----------------------------------
    if re.match(r"^Conference [Ww]ith Labor Negotiators", t):
        um = re.search(r"Employee Organizations?:\s*(.+)$", t)
        union = clean_ws(um.group(1)).rstrip(".") if um else "employee bargaining units"
        union = re.split(r";", union)[0]
        return "Governance", f"Authorizes closed-session labor negotiations with {union}."

    # -- Conference with Legal Counsel --------------------------------------
    if re.match(r"^Conference [Ww]ith Legal Counsel", t):
        kind = "potential" if "potential" in t.lower() else "existing"
        cm = re.search(r"Case Name:\s*([^;]+)", t)
        defm = re.search(r"(?:Potential )?Defendant:\s*([^;]+)", t)
        plm = re.search(r"Plaintiffs?:\s*([^;]+)", t)
        detail = None
        if cm:
            detail = clean_ws(cm.group(1))
        elif defm:
            detail = f"a potential claim against {clean_ws(defm.group(1))}"
        elif plm:
            detail = f"a claim brought by {clean_ws(plm.group(1))}"
        base = f"Authorizes closed-session discussion of {kind} litigation"
        return "Governance", f"{base} ({detail})." if detail else f"{base}."

    # -- Public Employee Appointment/Hiring ----------------------------------
    if re.match(r"^Public Employee Appointment/Hiring", t):
        pm = re.search(r"Positions? to be Filled:\s*(.+)$", t)
        pos = clean_ws(pm.group(1)).rstrip(".") if pm else "a city position"
        return "Governance", f"Authorizes closed-session discussion of hiring for {pos}."

    # -- Public Employee Performance Evaluation(s) ---------------------------
    if re.match(r"^Public Employee Performance Evaluations?", t):
        pm = re.search(r"Positions? Evaluated:\s*(.+)$", t)
        pos = clean_ws(pm.group(1)).rstrip(".") if pm else "city appointees"
        return "Governance", f"Authorizes closed-session performance evaluation of {pos}."

    # -- Recommendation to Approve <names> as Real Property/Labor Negotiators --
    if re.search(r"as (?:Real Property|Labor) Negotiators", t):
        is_rp = "Real Property Negotiators" in t
        fm = re.search(r"Negotiators for (?:the )?(.+)$", t)
        subj = strip_trailing_status(clean_ws(fm.group(1))) if fm else None
        cat = "Economic Development" if is_rp else "Governance"
        if subj:
            return cat, f"Designates city staff as negotiators for {lc_first(subj)}."
        return cat, "Designates city staff as negotiators for an upcoming closed-session negotiation."

    # -- Recommendation to Accept the Work of <contractor> for <project> ----
    m = re.match(r"^Recommendation to Accept the Work of (.+?) for (?:the )?(.+)$", t)
    if m:
        contractor, project = clean_ws(m.group(1)), strip_trailing_status(clean_ws(m.group(2)))
        return categorize(project), f"Accepts completed construction work by {contractor} on {project}."

    # -- Recommendation to Authorize .* to Execute ... -----------------------
    # Anchored to the START of the title: compound titles like "Recommendation
    # to Receive a Report...; and Authorize the City Manager to Execute..."
    # have "Receive a Report" as the actual lead action, and a bare re.search
    # would wrongly let the second, subordinate clause win just because it
    # appears somewhere in the string.
    if re.match(r"^Recommendation to Authorize (?:the )?(?:Interim )?City Manager.{0,20}to Execute", t) or \
       re.match(r"^Recommendation to Authorize (?:the )?City Attorney.{0,20}to Execute", t):
        rest = strip_trailing_status(t)
        summary = simplify_contract_clause(rest)
        cat = categorize(rest)
        if summary:
            return cat, summary
        rest2 = re.sub(r"^Recommendation to Authorize (?:the )?(?:Interim )?City (?:Manager|Attorney).{0,20}to Execute\s*", "", rest)
        return cat, f"Authorizes {lc_first(rest2)}." if rest2 else None

    # -- Recommendation to Authorize the City Manager to Purchase/Reject/... --
    m = re.match(r"^Recommendation to Authorize (?:the )?(?:Interim )?City Manager to (.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Authorizes the City Manager to {lc_first(rest)}."

    # -- Recommendation to Award / Ratify / Reaffirm / Endorse / Provide direction
    m = re.match(r"^Recommendation to (Award|Ratify|Reaffirm|Endorse|Provide Direction on|Adopt) (.+)$", t)
    if m:
        verb, rest = m.group(1), strip_trailing_status(clean_ws(m.group(2)))
        conj = "Provides direction on" if verb == "Provide Direction on" else third_person(verb)
        special = contract_vendor_effect(f"{verb} {rest}")
        return categorize(rest), special or f"{conj} {lc_first(rest)}."

    # -- Recommendation to Accept / Receive (reports) ------------------------
    m = re.match(r"^Recommendation to (Accept|Receive)(?: an)?(?: and [Ff]ile)? (.+)$", t)
    if m:
        verb, rest = m.group(1), strip_trailing_status(clean_ws(m.group(2)))
        return categorize(rest), f"{verb}s {lc_first(rest)}."

    # -- Recommendation to Approve <policy/plan/report> ----------------------
    m = re.match(r"^Recommendation to Approve (?:the )?(.+)$", t)
    if m and "Negotiators" not in t:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Approves {lc_first(rest)}."

    # -- Recommendation to Authorize (generic catch-all not matched above) --
    m = re.match(r"^Recommendation to Authorize(?:ing)? (?:the )?(.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), contract_vendor_effect(f"Authorize {rest}") or f"Authorizes {lc_first(rest)}."

    # -- Summary [Title]: ... ---------------------------------------------------
    m = re.match(r"^SUMMARY:?\s*(?:Title:\s*)?(.+)$", t, re.I)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"{rest}."

    # -- Designation of [a] Voting Delegate(s) --------------------------------
    if re.match(r"^Designation of a? ?Voting Delegate", t, re.I):
        return "Governance", "Designates the city's voting delegates and alternates for the League of California Cities conference."

    # -- Public Hearing to Establish the Proposition 4 (Appropriations) Limit
    # -- any fiscal year, so a regex replaces the year-by-year MANUAL entries.
    # Tolerant of case and the occasional clerk typo in the "(FY)" aside.
    m = re.search(r"Proposition 4 \(Appropriations\) Limit for Fiscal [Yy]ear.*?(\d{4}-\d{2})", t)
    if m:
        return "Budget & Finance", f"Sets the constitutional (Proposition 4) limit on city spending growth for Fiscal Year {m.group(1)}."

    # -- Set/Notice of/Call for a Public Hearing on <date> to/- <topic> ------
    m = re.match(r"^Set a Public Hearing on (.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Schedules a public hearing: {lc_first(rest)}."
    m = re.match(r"^Notice of Public Hearing on (.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Notice of a scheduled public hearing: {lc_first(rest)}."
    m = re.match(r"^Call for a Public Hearing\s*(.*)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return "Governance", f"Schedules a public hearing{', ' + rest[0].lower() + rest[1:] if rest else '.'}"

    # -- Presentation(s) on/by/of ... ------------------------------------------
    m = re.match(r"^Presentations? (?:on|by|of) (.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Presentation: {lc_first(rest)}."

    # -- Select One of the Following Options: ... ------------------------------
    m = re.match(r"^Select One of the Following[^:]*:\s*(.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Asks Council to choose among options: {lc_first(rest)}."

    # -- Selecting .../ Selection of ... ----------------------------------------
    m = re.match(r"^Selecting (.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Selects {lc_first(rest)}."
    m = re.match(r"^Selection of (.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Selects {lc_first(rest)}."

    # -- Bare verb-first titles missing their usual "Recommendation to" lead-in
    m = re.match(r"^(Approve|Authorize|Appropriate|Appropriation of)\s+(.+)$", t)
    if m:
        verb, rest = m.group(1), strip_trailing_status(clean_ws(m.group(2)))
        verbed = {"Approve": "Approves", "Authorize": "Authorizes",
                  "Appropriate": "Appropriates",
                  "Appropriation of": "Appropriates"}[verb]
        return categorize(rest), f"{verbed} {lc_first(rest)}."

    # -- Receive Report on .../ Report on ... -----------------------------------
    m = re.match(r"^Receive Report on (?:the )?(.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Receives a report on {lc_first(rest)}."
    m = re.match(r"^Report on (.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Report on {lc_first(rest)}."

    # -- Response to City Council Referral Regarding ... ------------------------
    m = re.match(r"^Response to City Council Referral Regarding (.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Responds to a council referral regarding {lc_first(rest)}."

    # -- Update on ... -----------------------------------------------------------
    m = re.match(r"^Update on (?:the )?(.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Update on {lc_first(rest)}."

    # -- <Subject> Annual Report (bare noun-phrase titles) ----------------------
    m = re.match(r"^(.+ Annual Report)\.?$", t)
    if m:
        return categorize(t), f"Receives the {clean_ws(m.group(1))}."

    # -- Written Communication from ... ----------------------------------------
    m = re.match(r"^Written Communication from (.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return "Governance", f"Responds to a written communication from {lc_first(rest)}."

    # -- Recommendation for/that/on City Council ... (alternate lead-in verbs) -
    m = re.match(r"^Recommendation (?:for City Council to|on City Council'?s?) (.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Recommends {lead_gerund(rest)}."
    m = re.match(r"^Recommendation that (.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Recommends that {lc_first(rest)}."

    # -- Proclamation ----------------------------------------------------------
    m = re.match(r"^Proclamation Declaring (.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return "Governance", f"Proclaims {lc_first(rest)}."

    # -- Closed Session - <topic> (generic; specific topics get MANUAL entries
    # above when a plainer summary is warranted) --------------------------
    m = re.match(r"^Closed Session\s*-\s*(.+)$", t)
    if m:
        topic = strip_trailing_status(clean_ws(m.group(1)))
        return "Governance", f"Authorizes closed-session discussion regarding {topic}."

    # -- Consideration of Mayor's Nominations for board/commission seats ---
    if t.startswith("Consideration of Mayor's Nominations"):
        rest = re.sub(r"^Consideration of Mayor's Nominations for Appointment to (?:the )?", "", t)
        rest = strip_trailing_status(clean_ws(rest))
        return "Governance", f"Considers the Mayor's nominations to fill seats on the {rest}."

    # -- Consider <doing something> -- referral-style items that ask Council
    # to weigh in on a course of action rather than adopt a specific measure
    m = re.match(r"^Consider(?:ing|ation of)?:?\s+(.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Asks Council to consider {lc_first(rest)}."

    # -- Recommendation to <verb> (broad catch-all; specific verbs above get
    # more natural phrasing -- this is a safety net, not a first choice) ----
    m = re.match(r"^Recommendation to:?\s+(.+)$", t)
    if m:
        rest = strip_trailing_status(clean_ws(m.group(1)))
        return categorize(rest), f"Recommends {lead_gerund(rest)}."

    return None, None  # no template matched -- needs a manual override


