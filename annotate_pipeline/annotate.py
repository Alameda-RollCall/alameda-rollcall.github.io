def final_category(title, cat):
    """Apply the precedence above to the full title; `cat` is the first-pass result."""
    t = STREET_NAMES.sub(" ", (title or "")).lower()
    for c, pat in PREPASS_RULES[:3]:       # appointments/city operations, business areas, land use
        if re.search(pat, t):
            return c
    if CONTRACT_FORM.search(t) and CONTRACT_LEAD.search(t) and not NOT_CONTRACT.search(t):
        for c, pat in CONTRACT_SUBJECTS:
            if re.search(pat, t):
                return c
        return "Contracts & Purchasing"
    for c, pat in PREPASS_RULES[3:]:       # leases/real property, finance, housing
        if re.search(pat, t):
            return c
    return cat


